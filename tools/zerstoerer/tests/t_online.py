"""Online-Koop über den lokalen Vermittler: Verbinden, Gebietswechsel, Skalierung, Boss, Gast-Angriff, Fallen/Wiederbeleben,
Verbindungsabbruch mit Wiederverbinden, Paketverlust, Gutschrift beim Gast, Ende. Braucht peer-server.js (ZS_PEER_PORT)."""
import sys
from playwright.sync_api import sync_playwright
from gemeinsam import Pruefung, browser_starten, warte
from online import seite, verbinden, TUER

T = Pruefung("online")
with sync_playwright() as p:
    b = browser_starten(p)
    H = seite(T, b, "H"); G = seite(T, b, "G")
    if not verbinden(T, H, G, "G"):
        T.ende()
    ev = lambda pg, js: pg.evaluate(js)
    real0 = ev(G, "Z.online.S.metaReal.shards")
    ev(H, "Z.meta.tut=true; Z.startRun()")
    warte(H, "Z.level.id!=='lager'", 15000)
    T.check("Gebiet 1 beim Gast", warte(G, "Z.level.id!=='lager'", 15000) and warte(G, "Z.online.S.levelOk", 5000), ev(G, "Z.level.id"))
    G.wait_for_timeout(1500)
    he = ev(H, "Z.enemies.filter(e=>Math.abs(e.x-Z.player.x)<700&&Math.abs(e.y-Z.player.y)<450).length"); ge = ev(G, "Z.enemies.length")
    T.check("Gegner in der Nähe gespiegelt", ge > 0 and abs(he - ge) <= 3, "Gastgeber %s, Gast %s" % (he, ge))
    sc = ev(H, "(()=>{const e=Z.enemies.find(e=>!e.dummy&&!e.def.boss);return e?[e._koopK,e.hpMax]:null})()")
    T.check("Koop-Skalierung normale Gegner (×1,5)", sc and abs((sc[0] or 1) - 1.5) < 0.01, sc)
    for hop in range(2):
        a0 = ev(H, "Z.level.id"); ev(H, TUER)
        ok = warte(H, "Z.level.id!=='%s'" % a0, 8000); a1 = ev(H, "Z.level.id")
        T.check("Gebietswechsel %d (%s → %s) beim Gast" % (hop + 1, a0, a1), ok and warte(G, "Z.level.id==='%s'" % a1, 8000))
        G.wait_for_timeout(800)
    ev(H, "Z.ui.modalOpen&&Z.ui.close(); __z.area('labor')")
    T.check("Arena beim Gast", warte(G, "Z.level.id==='labor'", 8000))
    ev(H, "__z.god(true); Z.player.x=20*16;")
    ok = warte(H, "!!Z.boss", 8000) and warte(H, "Z.boss._koopK>1 && !(Z.boss.intro>0)", 20000)
    bh = ev(H, "Z.boss&&[Z.boss.id,Math.round(Z.boss.hpMax),Z.boss._koopK]")
    T.check("Boss beim Gastgeber, HP ×1,8–2,0", ok and bh and 1.75 <= (bh[2] or 0) <= 2.05, bh)
    T.check("Boss beim Gast sichtbar", warte(G, "!!Z.boss && Z.boss.hpMax>0", 6000))
    hp0 = ev(H, "Z.boss.hp"); ev(H, "Z.koop.p2.x=Z.boss.x-30;Z.koop.p2.y=Z.boss.y+Z.boss.h-Z.koop.p2.h")
    d0 = ev(H, "Z.koop.stats?Z.koop.stats.dmg:0")
    for i in range(4):
        G.keyboard.down("KeyJ"); G.wait_for_timeout(350); G.keyboard.up("KeyJ"); G.wait_for_timeout(250)
    G.wait_for_timeout(1200)
    d1 = ev(H, "Z.koop.stats?Z.koop.stats.dmg:0"); hp1 = ev(H, "Z.boss?Z.boss.hp:0")
    T.check("Gast-Angriff trifft Boss beim Gastgeber", hp1 < hp0 or d1 > d0, "%s → %s" % (round(hp0), round(hp1)))
    gb = ev(G, "Z.boss?Math.round(Z.boss.hp):-1")
    T.check("Boss-HP beim Gast nachgezogen", abs(gb - hp1) < hp0 * 0.15 + 5, "Gast %s, Gastgeber %s" % (gb, round(hp1)))
    ev(H, "__z.god(false); Z.koop.p2.iframe=0; Z.koop.hurt(99999,{force:true,unblockable:true}); __z.god(true)")
    T.check("Spieler 2 fällt (Gast sieht es)", warte(G, "Z.koop.p2&&Z.koop.p2.down", 5000))
    ev(H, "Z.koop.p2.x=Z.player.x+6; Z.koop.p2.y=Z.player.y+Z.player.h-Z.koop.p2.h")
    H.keyboard.down("KeyE"); ok = warte(H, "!Z.koop.p2.down", 12000); H.keyboard.up("KeyE")
    if not ok:
        ev(H, "Z.koop.p2.revive=0.99"); ok = warte(H, "!Z.koop.p2.down", 6000)
    T.check("Spieler 2 wiederbelebt (Gast sieht es)", ok and warte(G, "Z.koop.p2&&!Z.koop.p2.down", 5000))
    ev(G, "Z.online.S.link.close()")
    T.check("Gastgeber merkt Abbruch", warte(H, "Z.online.S.st==='lost'", 9000))
    T.check("Gast verbindet sich wieder", warte(G, "Z.online.S.st==='play'", 20000) and warte(H, "Z.online.S.st==='play'", 10000), ev(G, "Z.online.S.st"))
    G.wait_for_timeout(1200)
    T.check("Schnappschüsse nach Wiederverbinden", warte(G, "Z.online.S.buf.length>3 && !!Z.boss", 6000))
    ev(H, "Z.online.test.sim({lat:120,jit:40,loss:0.25})"); ev(G, "Z.online.test.sim({lat:120,jit:40,loss:0.25})")
    s0 = ev(G, "Z.online.S.stats.snaps"); x0 = ev(H, "Z.koop.p2.x")
    G.keyboard.down("KeyA"); G.wait_for_timeout(1500); G.keyboard.up("KeyA"); G.wait_for_timeout(600)
    s1 = ev(G, "Z.online.S.stats.snaps"); x1 = ev(H, "Z.koop.p2.x")
    T.check("Unter 25 % Verlust + 120 ms: Bewegung kommt an", x1 < x0 - 10, "%d → %d" % (x0, x1))
    T.check("Unter Verlust weiter Schnappschüsse", s1 - s0 > 8, s1 - s0)
    gx = ev(G, "Z.koop.p2.x"); T.check("Gast-Sicht folgt (Abweichung < 60 px)", abs(gx - x1) < 60, "%d / %d" % (gx, x1))
    ev(H, "Z.online.test.sim(null)"); ev(G, "Z.online.test.sim(null)")
    ev(H, "Z.boss.hp=0")
    T.check("Boss besiegt – Gast sieht es", warte(G, "Z.bossDefeated", 6000))
    ev(H, "Z.meta.shards+=200"); G.wait_for_timeout(2500)
    ev(G, "Z.online.end('test')"); G.wait_for_timeout(500)
    real1 = ev(G, "Z.meta.shards"); cr = ev(G, "Z.online.S.lastCredit")
    T.check("Gutschrift beim Gast, gedeckelt", cr and 0 < cr <= 800 and real1 == real0 + cr, "vorher %s, nachher %s, Gutschrift %s" % (real0, real1, cr))
    T.check("Gastgeber merkt Ende", warte(H, "Z.online.S.st==='end' || !Z.online.S.role", 8000), ev(H, "Z.online.S.st"))
    T.check("Gastgeber spielt allein weiter", warte(H, "!Z.koop.p2", 3000))
    T.keine_seitenfehler()
    b.close()
T.ende()
