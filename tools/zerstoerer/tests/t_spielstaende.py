"""Spielstände (3 Plätze): Lauf in Platz 1, neues Spiel in Platz 2, wechseln, kopieren, zweistufig löschen, überschreiben."""
import json
from playwright.sync_api import sync_playwright
from gemeinsam import Pruefung, URL, browser_starten, warte

T = Pruefung("spielstaende")
def R(pg, n): return pg.evaluate("localStorage.getItem('imres-zerstoerer-s%d-v1')" % n)
def zum_titel(pg, frage=False):
    pg.evaluate("Z.ui.modalOpen && Z.ui.close(); Z.ui.pause()"); pg.wait_for_timeout(250); pg.click("[data-act=toTitle]"); pg.wait_for_timeout(300)
    if frage: pg.click("[data-act=confirmOk]")
    pg.wait_for_timeout(900)
def lauf(pg):
    pg.evaluate("Z.ui.close(); Z.meta.tut = true; __z.start()"); pg.wait_for_timeout(1500); pg.evaluate("Z.ui.close()")

with sync_playwright() as p:
    b = browser_starten(p)
    pg = T.seite(b, "s")
    pg.goto(URL); pg.wait_for_function("window.Z && Z.ui && window.__z", timeout=30000); pg.wait_for_timeout(600)
    pg.click("#t-play"); pg.wait_for_timeout(800); lauf(pg)
    pg.evaluate("Z.meta.shards += 300; Z.achTest.force(Z.achTest.list()[1].id); Z.meta.cape = 'rot'; Z.saveMeta()")
    pg.evaluate("Z.ui.pause()"); pg.wait_for_timeout(250); pg.click("[data-act=toTitle]"); pg.wait_for_timeout(300)
    T.check("Rückfrage beim Verlassen eines Laufs", "Titel" in pg.inner_text("#modal h2"), pg.inner_text("#modal h2"))
    pg.click("[data-act=confirmOk]"); pg.wait_for_timeout(1000)
    T.check("Titel sichtbar, kein Lauf", pg.evaluate("!document.getElementById('title').hidden && !Z.level && !Z.run"))
    s1 = R(pg, 1); m1 = json.loads(s1)
    T.check("Platz 1 gespeichert", m1["runs"] == 1 and m1["shards"] >= 300 and len(m1["ach"]) == 1, (m1["runs"], m1["shards"], len(m1["ach"])))
    pg.click("#t-slots"); pg.wait_for_timeout(400); pg.click("[data-act=slotNeu][data-arg='2']"); pg.wait_for_timeout(1000)
    T.check("Neues Spiel in Platz 2", pg.evaluate("Z.slots.active() === 2 && Z.level && Z.level.id === 'lager' && Object.keys(Z.meta.ach).length === 0 && Z.meta.shards === 0"))
    pg.evaluate("Z.ui.close(); Z.meta.tut = true; Z.meta.shards = 500; Z.ui.actions.up('zaeh'); Z.ui.close(); Z.achTest.force(Z.achTest.list()[5].id); Z.saveMeta()")
    lauf(pg); zum_titel(pg, True)
    m2 = json.loads(R(pg, 2))
    T.check("Platz 2 gespeichert (Lauf, Kauf, Erfolg)", m2["runs"] == 1 and m2["up"]["zaeh"] == 1 and len(m2["ach"]) == 1 and m2["shards"] < 500, (m2["runs"], m2["up"].get("zaeh"), list(m2["ach"]), m2["shards"]))
    T.check("Platz 1 unverändert", R(pg, 1) == s1)
    T.check("Titel nennt Platz 2", "Spielstand 2" in pg.inner_text("#t-play"), pg.inner_text("#t-play").replace("\n", " | "))
    pg.click("#t-slots"); pg.wait_for_timeout(400); pg.click("[data-act=slotSpielen][data-arg='1']"); pg.wait_for_timeout(1000)
    T.check("Platz 1 geladen", pg.evaluate("Z.slots.active() === 1 && Z.meta.shards === %d && !Z.meta.up.zaeh" % m1["shards"]))
    zum_titel(pg)
    s1 = R(pg, 1)
    pg.click("#t-slots"); pg.wait_for_timeout(400); pg.click("[data-act=slotKopie][data-arg='1']"); pg.wait_for_timeout(300)
    pg.click("[data-act=slotKopieZiel][data-arg='1:3']"); pg.wait_for_timeout(400)
    T.check("Kopie 1 → 3", R(pg, 3) == R(pg, 1) and pg.evaluate("!!document.querySelector('.sl-liste')"))
    pg.click("[data-act=slotKopie][data-arg='2']"); pg.wait_for_timeout(300); pg.click("[data-act=slotKopieZiel][data-arg='2:3']"); pg.wait_for_timeout(300)
    T.check("Rückfrage vor Überschreiben, Fokus auf Abbrechen", "überschreiben" in pg.inner_text("#modal h2") and pg.evaluate("document.activeElement.textContent") == "Abbrechen")
    pg.keyboard.press("Escape"); pg.wait_for_timeout(300)
    T.check("Esc bricht ab", pg.evaluate("!!document.querySelector('.sl-liste')") and R(pg, 3) == R(pg, 1))
    pg.click("[data-act=slotWeg][data-arg='2']"); pg.wait_for_timeout(300); h1 = pg.inner_text("#modal h2")
    pg.click("[data-act=slotJa]"); pg.wait_for_timeout(300); h2 = pg.inner_text("#modal h2")
    T.check("Löschen zweistufig", "löschen" in h1 and "endgültig" in h2 and R(pg, 2) is not None, (h1, h2))
    pg.click("[data-act=slotJa]"); pg.wait_for_timeout(400)
    T.check("Platz 2 gelöscht, Sicherung bleibt", R(pg, 2) is None and pg.evaluate("!!localStorage.getItem('imres-zerstoerer-s2-weg')"))
    pg.click("[data-act=slotNeu][data-arg='3']"); pg.wait_for_timeout(300)
    T.check("Überschreiben fragt nach", "überschreiben" in pg.inner_text("#modal h2"))
    pg.click("[data-act=slotJa]"); pg.wait_for_timeout(1000)
    T.check("Platz 3 neu", pg.evaluate("Z.slots.active() === 3 && Z.meta.runs === 0 && Object.keys(Z.meta.ach).length === 0 && Z.level.id === 'lager'") and R(pg, 1) == s1)
    zum_titel(pg)
    T.check("Spiegel für den Spielesaal = aktiver Platz", pg.evaluate("localStorage.getItem('imres-zerstoerer-v1') === localStorage.getItem(Z.slots.key(Z.slots.active()))"))
    pg.click("#t-slots"); pg.wait_for_timeout(300); pg.click("[data-act=slotWeg][data-arg='3']"); pg.wait_for_timeout(250); pg.click("[data-act=slotJa]"); pg.wait_for_timeout(250); pg.click("[data-act=slotJa]"); pg.wait_for_timeout(300)
    pg.keyboard.press("Escape"); pg.wait_for_timeout(400)
    T.check("Aktiven Platz gelöscht → Titel zeigt Platz 1", pg.evaluate("Z.slots.active()") == 1 and "Spielstand 1" in pg.inner_text("#t-play"), pg.inner_text("#t-play").replace("\n", " | "))
    T.keine_seitenfehler()
    b.close()
T.ende()
